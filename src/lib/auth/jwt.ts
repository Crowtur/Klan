import jwt from "jsonwebtoken";

const JWT_SECRET = process.env.JWT_SECRET;

if (!JWT_SECRET) {
  throw new Error("JWT_SECRET no está definido en las variables de entorno");
}

// Asignación explícita de tipo string para evitar problemas de narrowing dentro de funciones
const secret: string = JWT_SECRET;

export interface AuthTokenPayload {
  userId: string;
  email: string;
  globalRole: string;
}

/** Firma los datos de sesión con la clave privada de configuración del servidor. */
export function createAuthToken(payload: AuthTokenPayload): string {
  return jwt.sign(payload, secret, {
    expiresIn: "1d",
  });
}

/** Verifica la firma del JWT antes de utilizar los datos de identidad que contiene. */
export function verifyAuthToken(token: string): AuthTokenPayload {
  return jwt.verify(token, secret) as unknown as AuthTokenPayload;
}